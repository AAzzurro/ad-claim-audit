def main() -> None:
    gold = {
        str(r["sample_id"]): r
        for r in json.loads((OUT_DIR / "manual_annotation.json").read_text(encoding="utf-8"))
    }
    rows = []
    for item in ROWS:
        sid = item["sample_id"]
        rec = gold[sid]
        e1 = json.loads((ROOT / "data" / "detect" / f"{sid}.json").read_text(encoding="utf-8"))
        e2 = json.loads((ROOT / "data" / "classify" / f"{sid}.json").read_text(encoding="utf-8"))
        rows.append(
            {
                "样本编号": sid,
                "抽样原因": item["抽样原因"],
                "人工标签": item["人工标签"],
                "E1标签": "；".join(e1.get("risk_labels") or []),
                "E2标签": "；".join(e2.get("risk_labels") or []),
                "E1证据": " || ".join(e1.get("evidence") or [])[:200],
                "E2证据": " || ".join(e2.get("evidence") or [])[:200],
                "E1证据是否正确": item["E1证据是否正确"],
                "E2证据是否正确": item["E2证据是否正确"],
                "E1是否需要修改": item["E1是否需要修改"],
                "E2是否需要修改": item["E2是否需要修改"],
                "误判原因": item["误判原因"],
                "金标准说明": rec.get("人工说明") or "",
            }
        )

    df = pd.DataFrame(rows)
    csv_path = OUT_DIR / "review_20.csv"
    xlsx_path = OUT_DIR / "review_20.xlsx"
    json_path = OUT_DIR / "review_20.json"
    df.to_csv(csv_path, index=False, encoding="utf-8-sig")
    json_path.write_text(
        json.dumps(df.to_dict(orient="records"), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    summary = pd.DataFrame(
        [
            {"项目": "复核条数", "值": len(df)},
            {"项目": "E1需改", "值": int((df["E1是否需要修改"] == "是").sum())},
            {"项目": "E2需改", "值": int((df["E2是否需要修改"] == "是").sum())},
            {"项目": "E1证据正确或适用正确", "值": int(df["E1证据是否正确"].isin(["是", "部分"]).sum())},
            {"项目": "E2证据正确或适用正确", "值": int(df["E2证据是否正确"].isin(["是", "部分"]).sum())},
        ]
    )
    with pd.ExcelWriter(xlsx_path, engine="openpyxl") as writer:
        df.to_excel(writer, index=False, sheet_name="人工复核表")
        summary.to_excel(writer, index=False, sheet_name="复核摘要")

    print(f"n={len(df)} csv={csv_path} xlsx={xlsx_path}")
    print(summary.to_string(index=False))


if __name__ == "__main__":
    main()
